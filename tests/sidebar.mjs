import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
const modules = process.argv[2];
const load = path => import(pathToFileURL(`${modules}/${path}`).href);
const { createChatViewport } = await load("@earendil-works/pi-coding-agent/dist/modes/interactive/chat-viewport.js");
const { InteractiveMode } = await load("@earendil-works/pi-coding-agent/dist/modes/interactive/interactive-mode.js");
const { Container, TuiAltScreen, Text, ScrollView, VStack } = await load("@earendil-works/pi-tui/dist/index.js");
const { renderLayoutFrame, getScrollViewBox } = await load("@earendil-works/pi-tui/dist/layout.js");
const { initTheme, getMarkdownTheme } = await load("@earendil-works/pi-coding-agent/dist/modes/interactive/theme/theme.js");
initTheme("dark", false);
const doc = new Container(), chat = new Container();
doc.addChild(new Text("HEADER", 0, 0)); doc.addChild(chat);
const first = new Text("First message\n".repeat(10), 0, 0), target = new Text("Target message wraps as the terminal changes width. ".repeat(5), 0, 0);
chat.addChild(first); chat.addChild(target); chat.addChild(new Text("Later message\n".repeat(60), 0, 0));
const editor = new Text("EDITOR", 0, 0), footer = new Text("FOOTER", 0, 0), empty = new Container();
const todos = new Text("Todos\nTask one\nTask two\nTask three", 0, 0);
const pending = new Text("QUEUED", 0, 0), status = new Text("STATUS", 0, 0);
const viewport = createChatViewport({ document: doc, pendingMessages: pending, status, widgetsAbove: todos, editor, footer });
assert.equal(typeof viewport.setSidebar, "function");
const log = new ScrollView(new Text("SUMMARY\n".repeat(50), 0, 0), { follow: "end", overscroll: "contain" });
const panel = new VStack([{ component: log, grow: 1, basis: 0 }, new Text("NOW\nUSAGE", 0, 0)]);
const visible = [];
viewport.setSidebar(panel, undefined, value => visible.push(value));
let frame = renderLayoutFrame(viewport.root, 140, 24, () => {});
await Promise.resolve();
assert.deepEqual(visible, [true]);
assert.equal(getScrollViewBox(frame, viewport.transcript).rect.width, 96);
assert.equal(getScrollViewBox(frame, log).rect.width, 44);
assert.ok(frame.lines.some(line => line.startsWith("EDITOR")));
assert.ok(frame.lines.at(-1).startsWith("FOOTER"));
const find = (box, component) => box.component === component ? box : box.children.map(child => find(child, component)).find(Boolean);
assert.equal(find(frame.root, editor).rect.width, 140);
assert.equal(find(frame.root, footer).rect.width, 140);
assert.equal(find(frame.root, todos).rect.width, 96, "todos stay in the left column");
assert.equal(find(frame.root, pending).rect.width, 96);
assert.equal(find(frame.root, status).rect.width, 96);
const panelRect = find(frame.root, panel).rect;
assert.equal(panelRect.y + panelRect.height, find(frame.root, editor).rect.y, "sidebar ends immediately above the editor");
for (const columns of [100, 80, 60, 49, 48]) {
  frame = renderLayoutFrame(viewport.root, columns, 24, () => {});
  await Promise.resolve();
  const sidebarWidth = Math.min(44, Math.floor(columns / 2));
  assert.equal(getScrollViewBox(frame, log).rect.width, sidebarWidth);
  assert.equal(getScrollViewBox(frame, viewport.transcript).rect.width, columns - sidebarWidth);
  assert(sidebarWidth >= 24 && sidebarWidth <= columns / 2);
}
assert.deepEqual(visible, [true], "narrow terminals retain the sidebar");
frame = renderLayoutFrame(viewport.root, 48, 18, () => {});
await Promise.resolve();
assert(getScrollViewBox(frame, log), "minimum readable panel height still fits");
frame = renderLayoutFrame(viewport.root, 47, 24, () => {});
await Promise.resolve();
assert.deepEqual(visible, [true, false]);
assert.equal(getScrollViewBox(frame, viewport.transcript).rect.width, 47);
assert.equal(getScrollViewBox(frame, log), undefined);
assert.equal(find(frame.root, todos).rect.width, 47, "hidden sidebar restores full-width widgets");
const terminal = { columns: 140, rows: 24, start() {}, stop() {}, write() {}, hideCursor() {}, showCursor() {} };
const tui = new TuiAltScreen(terminal);
tui.requestRender = () => {};
tui.currentLayout = renderLayoutFrame(viewport.root, 140, 24, () => {});
const focus = { render: () => [""], focused: false };
tui.setFocus(focus);
assert.equal(tui.scrollToComponent(target), true);
assert.equal(viewport.transcript.scrollTop, doc.children[0].render(96).length + first.render(96).length);
assert.equal(viewport.transcript.isFollowingEnd, false);
assert.equal(focus.focused, true);
assert.equal(tui.scrollToComponent(new Text("not in this session", 0, 0)), false);
// Exercise the native API with a real branch entry and tool target, not row numbers.
const user = { role: "user", content: "source", timestamp: 1 };
const result = { role: "toolResult", toolCallId: "call", content: [], timestamp: 2 };
const mode = Object.assign(Object.create(InteractiveMode.prototype), {
 renderer: tui, ui: tui, chatViewport: viewport,
 messageComponents: new WeakMap([[user, target]]), historyTools: new Map([["call", target]]),
});
const entries = [{ id: "user", type: "message", message: user }, { id: "tool", type: "message", message: result }];
Object.defineProperty(mode, "sessionManager", { value: { getBranch: () => entries } });
const normalRender = target.render;
const normalRows = target.render(96);
assert.equal(mode.scrollToSessionEntry("user"), true);
assert.notEqual(target.render, normalRender, "jump destination is highlighted");
assert.equal(target.render(96).length, normalRows.length, "highlight does not reflow messages");
assert.deepEqual(target.render(96).map(row => row.replace(/\x1b\[[0-9;]*m/g, "")), normalRows);
assert.equal(mode.scrollToSessionEntry("tool"), true);
assert.equal(mode.scrollToSessionEntry("other-branch"), false);
const renderedUser = { role: "user", content: "A real rendered user message", timestamp: 1 };
mode.chatContainer = chat;
mode.outputPad = 0;
mode.getMarkdownThemeWithSettings = () => getMarkdownTheme();
mode.getMarkdownTransformers = () => [];
mode.addMessageToChat(renderedUser);
entries.push({ id: "rendered", type: "message", message: renderedUser });
assert.ok(mode.messageComponents.get(renderedUser));
tui.currentLayout = renderLayoutFrame(viewport.root, 140, 24, () => {});
assert.equal(mode.scrollToSessionEntry("rendered"), true);
assert.equal(focus.focused, true);
assert.equal(target.render, normalRender, "a new destination restores the previous message");
tui.highlightComponent(target, 10);
assert.notEqual(target.render, normalRender);
await new Promise(resolve => setTimeout(resolve, 25));
assert.equal(target.render, normalRender, "the pulse expires and restores normal rendering");
tui.highlightComponent(target);
tui.clearComponentHighlight();
assert.equal(target.render, normalRender, "session cleanup restores the message immediately");
let disposed = 0;
assert.equal(mode.setExtensionSidebar("minimap", () => ({ ...panel, render: width => panel.render(width), dispose: () => disposed++ })), true);
assert.equal(mode.setExtensionSidebar("other", () => panel), false);
assert.equal(mode.setExtensionSidebar("minimap", undefined), true);
assert.equal(disposed, 1);
// Removal also works after leaving fullscreen, so a hidden panel cannot reappear.
mode.renderer = {};
assert.equal(mode.setExtensionSidebar("minimap", () => panel), false);
assert.equal(mode.setExtensionSidebar("minimap", undefined), true);
frame = renderLayoutFrame(viewport.root, 140, 24, () => {});
assert.equal(getScrollViewBox(frame, viewport.transcript).rect.width, 140);
const staleVisibility = [];
viewport.setSidebar(panel, 38, shown => staleVisibility.push(shown));
renderLayoutFrame(viewport.root, 140, 24, () => {});
viewport.setSidebar(undefined);
await Promise.resolve();
assert.deepEqual(staleVisibility, [false], "removing a panel invalidates a queued visible callback");
viewport.setSidebar(panel);
frame = renderLayoutFrame(viewport.root, 140, 10, () => {});
assert.equal(getScrollViewBox(frame, log), undefined, "short terminals hide the sidebar too");
console.log("sidebar: layout, resize visibility, dock width, source navigation, branch rejection, focus, ownership and disposal passed");
